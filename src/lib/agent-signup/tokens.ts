/**
 * The two credentials an agent holds after it signs itself up (sign-up contract §2, Steps 2 and 3).
 *
 * - The identity assertion is the agent's lasting secret. It is minted once at registration, lasts 365 days, and is
 *   only ever sent to our token endpoint, where the agent trades it for an access token (RFC 7523 JWT bearer grant).
 * - The access token goes on every other call. It lasts one hour, and there is no refresh token: when it expires the
 *   agent trades the same assertion again. A leaked access token dies within the hour; a leaked assertion is stopped
 *   by revoking its registration row, which the token endpoint checks on every trade.
 *
 * How they are signed. Both are JWTs signed by Better Auth's jwt plugin, the same plugin and key table that already
 * sign Queue Pilot's connector tokens, so key generation, private-key encryption at rest, rotation and the public JWKS
 * are not reimplemented here. The plugin exposes `signJWT` and `verifyJWT` as server-only endpoints that take no
 * session (better-auth 1.7.15, dist/plugins/jwt/index.mjs, `createAuthEndpoint.serverOnly`), so a server route
 * can call `auth.api.signJWT` for an agent that has no person behind it. Every claim is set explicitly in the payload;
 * nothing relies on the plugin's defaults. The `jose` library the plugin uses internally is not a dependency of this
 * app, so it is not imported here.
 *
 * Why the two can never be swapped (RFC 8725 §3.12: give different kinds of JWT mutually exclusive validation rules):
 *
 *   |          | assertion                         | access token                      |
 *   | -------- | --------------------------------- | --------------------------------- |
 *   | purpose  | "identity_assertion"              | "access_token"                    |
 *   | iss      | {origin}/v1/agent/identity        | {origin}                          |
 *   | aud      | [{origin}, {origin}/v1/oauth2/token] | [{origin}, {origin}/v1/]       |
 *   | sub      | the registration id (reg_...)     | the registration id (reg_...)     |
 *   | lifetime | 365 days                          | 1 hour                            |
 *
 * The plugin's verifier checks the signature, expiry and issuer itself (the issuer is passed per call), so an access
 * token fails assertion verification before our own checks run, and the other way round. It also insists that `aud`
 * contains the site origin and cannot be told otherwise per call, which is why each `aud` is a list (RFC 7519 §4.1.3):
 * the origin the plugin requires, plus the audience that is ours to check. RFC 7523 §3 says an assertion's audience
 * names the authorization server and allows its token endpoint URL; RFC 9068 §2.2 says an access token's issuer is
 * the authorization server. The `purpose` claim plays the role a JOSE `typ` header would (RFC 8725 §3.11); the
 * plugin's server endpoint takes no header, so it travels in the payload and is checked here.
 *
 * Keep old signing keys. The plugin's verifier looks a token's key up among every row of the key table, with no
 * expiry filter (dist/plugins/jwt/adapter.mjs `getAllKeys`, verify.mjs). An assertion lives 365 days, so a key row
 * must not be deleted while assertions it signed are still live, even after a rotation stops it signing new ones.
 *
 * Telling an outage from a forgery. The plugin's verifier returns null for a bad signature and for an unreadable key
 * table alike. After a null we read the public keys once more (`getJwks`); if that read fails too, the reply is
 * "unavailable" and the agent keeps its credential. This narrows the window rather than closing it: the table could
 * fail on the first read and recover by the second. Two limits of the probe, neither true of today's configuration:
 * it creates a key when the table is empty, and it always throws when the plugin is set to use a remote JWKS
 * (`jwks.remoteUrl`), which would turn every refused token into "unavailable".
 *
 * What this module does not do: look at the registration row. Revoked, deleted or frozen accounts are decided by the
 * route that calls these functions, on every trade and every call (sign-up contract §4), because a signature alone
 * cannot know about a revoke that happened after signing.
 */
import { randomUUID } from "node:crypto";

export const ASSERTION_TTL_SECONDS = 365 * 24 * 60 * 60;
export const ACCESS_TOKEN_TTL_SECONDS = 60 * 60;

/** Registration ids are generated by us; anything else in `sub` is someone else's token. */
export const REGISTRATION_ID = /^reg_[A-Za-z0-9_-]{1,64}$/;

type Kind = "identity_assertion" | "access_token";
type Claims = Record<string, unknown>;

/**
 * The slice of a Better Auth instance (with the jwt plugin) that these functions use. Taking it as a parameter keeps
 * this module free of configuration and lets tests pass the real instance or a deliberately broken one.
 */
export type AgentTokenSigner = {
  api: {
    signJWT(args: { body: { payload: Claims } }): Promise<{ token: string }>;
    verifyJWT(args: { body: { token: string; issuer?: string } }): Promise<{ payload: Claims | null }>;
    getJwks(): Promise<unknown>;
  };
};

export type IssuedToken = { token: string; jti: string; expiresAt: Date };
export type VerifiedToken = { ok: true; registrationId: string; jti: string; expiresAt: Date };
/**
 * Why a token was refused. The route maps these to the contract's errors:
 * - invalid: invalid_grant for an assertion (the agent drops it), unauthorized for an access token.
 * - expired: invalid_grant for an assertion, token_expired for an access token (the agent trades again).
 * - unavailable: internal_error, retryable. The agent keeps its credential.
 */
export type RefusedToken = { ok: false; reason: "invalid" | "expired" | "unavailable" };

function rules(kind: Kind, baseURL: string) {
  const origin = new URL(baseURL).origin;
  return kind === "identity_assertion"
    ? { origin, issuer: `${origin}/v1/agent/identity`, audience: `${origin}/v1/oauth2/token`, ttl: ASSERTION_TTL_SECONDS }
    : { origin, issuer: origin, audience: `${origin}/v1/`, ttl: ACCESS_TOKEN_TTL_SECONDS };
}

async function issue(signer: AgentTokenSigner, kind: Kind, opts: { baseURL: string; registrationId: string; now?: Date }): Promise<IssuedToken> {
  if (!REGISTRATION_ID.test(opts.registrationId)) throw new Error("Agent tokens are issued only to registration ids (reg_...)");
  const r = rules(kind, opts.baseURL);
  const iat = Math.floor((opts.now ?? new Date()).getTime() / 1000);
  const exp = iat + r.ttl;
  const jti = randomUUID();
  const { token } = await signer.api.signJWT({
    body: { payload: { purpose: kind, iss: r.issuer, aud: [r.origin, r.audience], sub: opts.registrationId, jti, iat, exp } },
  });
  return { token, jti, expiresAt: new Date(exp * 1000) };
}

/**
 * Reads a JWT's claims without checking its signature. Used only after verification has already failed, to choose
 * between "expired" and "invalid" in the reply. A forger can make us say "expired" instead of "invalid", which
 * tells them nothing and grants nothing: both are refusals.
 */
const isClaims = (v: unknown): v is Claims => typeof v === "object" && v !== null;

function unverifiedClaims(token: string): Claims | null {
  const parts = token.split(".");
  if (parts.length !== 3) return null;
  try {
    const claims: unknown = JSON.parse(Buffer.from(parts[1], "base64url").toString("utf8"));
    return isClaims(claims) ? claims : null;
  } catch {
    return null;
  }
}

async function verify(signer: AgentTokenSigner, kind: Kind, opts: { baseURL: string; token: string }): Promise<VerifiedToken | RefusedToken> {
  const r = rules(kind, opts.baseURL);
  let payload: Claims | null;
  try {
    ({ payload } = await signer.api.verifyJWT({ body: { token: opts.token, issuer: r.issuer } }));
  } catch {
    return { ok: false, reason: "unavailable" };
  }

  if (!payload) {
    // The plugin returns null for a bad signature and for a key table it could not read alike
    // (dist/plugins/jwt/verify.mjs wraps both in one try). Reading the public keys again tells them apart: if that
    // read fails too, the problem is ours, and the agent must keep its credential (sign-up contract §13).
    try {
      await signer.api.getJwks();
    } catch {
      return { ok: false, reason: "unavailable" };
    }
    const c = unverifiedClaims(opts.token);
    const looksLikeOurs = c?.purpose === kind && c.iss === r.issuer;
    const expired = looksLikeOurs && typeof c.exp === "number" && c.exp * 1000 <= Date.now();
    return { ok: false, reason: expired ? "expired" : "invalid" };
  }

  // Signature, expiry, issuer and the origin audience were checked by the plugin. These are the checks that are ours.
  const aud = Array.isArray(payload.aud) ? payload.aud : [payload.aud];
  const { sub, jti, exp } = payload;
  const ok =
    payload.purpose === kind &&
    payload.iss === r.issuer &&
    aud.includes(r.audience) &&
    typeof sub === "string" &&
    REGISTRATION_ID.test(sub) &&
    typeof jti === "string" &&
    jti.length > 0 &&
    typeof exp === "number";
  if (!ok) return { ok: false, reason: "invalid" };
  return { ok: true, registrationId: sub, jti, expiresAt: new Date(exp * 1000) };
}

/** Mints the 365-day identity assertion returned once by registration (POST /v1/agent/identity). Store its jti. */
export function issueIdentityAssertion(signer: AgentTokenSigner, opts: { baseURL: string; registrationId: string; now?: Date }): Promise<IssuedToken> {
  return issue(signer, "identity_assertion", opts);
}

/** Checks an identity assertion presented to the token endpoint. The caller must then check the registration row. */
export function verifyIdentityAssertion(signer: AgentTokenSigner, opts: { baseURL: string; token: string }): Promise<VerifiedToken | RefusedToken> {
  return verify(signer, "identity_assertion", opts);
}

/** Mints a one-hour access token (POST /v1/oauth2/token). There is deliberately no refresh token. */
export async function issueAccessToken(
  signer: AgentTokenSigner,
  opts: { baseURL: string; registrationId: string; now?: Date },
): Promise<IssuedToken & { expiresIn: typeof ACCESS_TOKEN_TTL_SECONDS }> {
  return { ...(await issue(signer, "access_token", opts)), expiresIn: ACCESS_TOKEN_TTL_SECONDS };
}

/** Checks the Bearer token on an agent call. The caller must then check the registration row. */
export function verifyAccessToken(signer: AgentTokenSigner, opts: { baseURL: string; token: string }): Promise<VerifiedToken | RefusedToken> {
  return verify(signer, "access_token", opts);
}
