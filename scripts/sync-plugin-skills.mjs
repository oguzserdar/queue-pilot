// Writes src/lib/plugin-skills.ts from plugin/skills, so the skills the setup prompt installs and the skills the
// plugin ships are one set. Run it after editing a plugin skill; plugin-skills.test.ts fails when it was forgotten.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";

/** The generated module's text, in the order the folders sort. */
export function render(root = "plugin/skills") {
  const names = readdirSync(root, { withFileTypes: true }).filter((d) => d.isDirectory()).map((d) => d.name).sort();
  const entries = names.map((n) => `  ${JSON.stringify(n)}: ${JSON.stringify(readFileSync(`${root}/${n}/SKILL.md`, "utf8"))},`);
  return `/**
 * Generated by scripts/sync-plugin-skills.mjs from plugin/skills. Do not edit by hand.
 * The task skills the plugin ships, served from /.well-known/agent-skills so every install route gets the same set.
 */
export const PLUGIN_SKILLS: Record<string, string> = {
${entries.join("\n")}
};
`;
}

if (process.argv[1]?.endsWith("sync-plugin-skills.mjs")) writeFileSync("src/lib/plugin-skills.ts", render());
